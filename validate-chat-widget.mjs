import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import crypto from 'node:crypto';
const partial = fs.readFileSync('assets/partials/chat-widget.html','utf8').trim();
for (const file of fs.readdirSync('.').filter(f=>f.endsWith('.html'))) {
 const html=fs.readFileSync(file,'utf8');
 assert.ok(html.includes(partial),`${file}: shared widget`);
 assert.equal([...html.matchAll(/data-chat-widget/g)].length,1);
 assert.ok(!/<iframe/.test(html),'No iframe loaded in static markup');
}
assert.equal(crypto.createHash('sha256').update(fs.readFileSync('assets/images/its-logo.png')).digest('hex').toUpperCase(),'F34231A6B42233B59EEFC59D5F19D593D0EC38114BE03797C05CAAAE7CDEA347');
const element = () => ({events:{},attrs:{},hidden:true,style:{setProperty(){}},addEventListener(name,fn){this.events[name]=fn;},setAttribute(k,v){this.attrs[k]=v;},focus(){this.focused=true;}});
const launcher=element(),panel=element(),close=element(),content=element(),status=element();
let created=0,frames=[];
content.append = frame=>frames.push(frame);
panel.showModal=()=>{panel.open=true;};
panel.close=()=>{panel.open=false;panel.events.close();};
const selectors={'.its-chat-launcher':launcher,'.its-chat-panel':panel,'.its-chat-close':close,'.its-chat-content':content,'.its-chat-status':status};
const widget={querySelector:key=>selectors[key],style:{setProperty(){}}};
const document={querySelector:()=>widget,querySelectorAll:()=>[],createElement:()=>{created++;return element();},addEventListener(){}};
const source=fs.readFileSync('assets/js/main.js','utf8').split('// Embed the existing assistant only after a visitor chooses to open it.')[1];
vm.runInNewContext(source,{document,window:{addEventListener(){},innerHeight:800},setTimeout:()=>1,clearTimeout(){}});
assert.equal(created,0);
launcher.events.click();
assert.equal(created,1);
assert.equal(frames[0].title,'ITSIPL Assistant');
assert.equal(frames[0].attrs.allow,'microphone https://company-chatbot-5c6r.onrender.com');
assert.equal(frames[0].src,'https://company-chatbot-5c6r.onrender.com/');
const original=frames[0];
frames[0].events.load();
assert.equal(status.hidden,true);
close.events.click();
assert.equal(panel.open,false);
assert.equal(launcher.focused,true);
launcher.events.click();
assert.equal(created,1);
assert.equal(frames[0],original);
panel.events.cancel({preventDefault(){}});
assert.equal(panel.open,false);
assert.equal(launcher.attrs['aria-expanded'],'false');
console.log('13 pages: shared widget, lazy iframe, close/reopen retention, dialog cancel, focus return, microphone origin, and unchanged ITS logo passed.');
console.log('These are controller tests; rendering, iframe keyboard events, touch, and voice require a connected browser.');
